package library

import "testing"

func TestRuStreet(t *testing.T) {
	cases := map[string]string{
		"Фуркат улица":            "улица Фуркат",
		"Амира Тимура проспект":   "проспект Амира Тимура",
		"Абая улица":              "улица Абая",
		"Тахтапуль Дарваза улица": "улица Тахтапуль Дарваза",
		"Чиланзарская улица":      "Чиланзарская улица",
		"2-я Паркентская улица":   "2-я Паркентская улица",
		"Малая кольцевая дорога":  "Малая кольцевая дорога",
		"Ферганское шоссе":        "Ферганское шоссе",
		"проспект Мирзо Улугбека": "проспект Мирзо Улугбека",
		"Сергели йули":            "Сергели йули",
	}
	for in, want := range cases {
		if got := ruStreet(in); got != want {
			t.Errorf("ruStreet(%q) = %q, want %q", in, got, want)
		}
	}
}
